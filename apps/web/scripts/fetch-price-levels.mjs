#!/usr/bin/env node
/**
 * Regenerates `packages/core/src/intelligence/reference/price-levels.ts` from the
 * World Bank's World Development Indicators.
 *
 *   node apps/web/scripts/fetch-price-levels.mjs
 *
 * WHAT IT COMPUTES. A price level ratio: how many US dollars buy, in a country,
 * what one US dollar buys in the United States (US = 1.0). It is the definition
 * of the archived WDI series PA.NUS.PPPC.RF ("Price level ratio of PPP
 * conversion factor (GDP) to market exchange rate"), which the live API no
 * longer serves — it moved to the "WDI Database Archives" source — so it is
 * rebuilt here from the two live series it is the ratio of:
 *
 *   household consumption level = PA.NUS.PRVT.PP / PA.NUS.FCRF
 *   GDP level                   = PA.NUS.PPP     / PA.NUS.FCRF
 *
 * The numerator and the exchange rate are always taken from the SAME year (the
 * most recent year 2018–2024 where both are published). The household
 * consumption level is the one the budget uses: it prices what households buy
 * (food, lodging, transport, recreation), which is closer to what a traveller
 * buys than GDP, whose basket includes investment and government spending. The
 * GDP level is kept beside it as a fallback and for audit.
 *
 * WHAT IT REFUSES. Aggregates (World Bank region "Aggregates") are dropped. A
 * ratio outside 0.1–3.0 is dropped and listed, never corrected: it marks a year
 * where the official exchange rate and the PPP series disagree about the
 * currency itself (a redenomination, a parallel market), and no traveller pays
 * a tenth of a cent for dinner. No country is ever adjusted by hand.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const OUT = fileURLToPath(new URL('../../../packages/core/src/intelligence/reference/price-levels.ts', import.meta.url));
const API = 'https://api.worldbank.org/v2';
const YEARS = '2018:2024';
const PLAUSIBLE = [0.1, 3.0];

async function json(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(60_000), headers: { accept: 'application/json' } });
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  const body = await response.json();
  if (!Array.isArray(body) || body.length < 2) throw new Error(`${url} answered ${JSON.stringify(body).slice(0, 300)}`);
  return body;
}

async function series(indicator) {
  const [meta, rows] = await json(`${API}/country/all/indicator/${indicator}?format=json&per_page=20000&date=${YEARS}`);
  const out = new Map();
  for (const row of rows) {
    if (row.value === null || row.value === undefined) continue;
    const byYear = out.get(row.countryiso3code) ?? new Map();
    byYear.set(row.date, row.value);
    out.set(row.countryiso3code, byYear);
  }
  return { lastUpdated: meta.lastupdated, values: out };
}

function levelFrom(numerator, fx) {
  if (!numerator || !fx) return null;
  const years = [...fx.keys()].filter((y) => numerator.has(y)).sort().reverse();
  const year = years[0];
  if (!year) return null;
  const ratio = numerator.get(year) / fx.get(year);
  return Number.isFinite(ratio) && ratio > 0 ? { ratio, year: Number(year) } : null;
}

const [, countries] = await json(`${API}/country?format=json&per_page=400`);
const [ppp, prvt, fcrf] = await Promise.all([series('PA.NUS.PPP'), series('PA.NUS.PRVT.PP'), series('PA.NUS.FCRF')]);

const rows = {};
const dropped = [];
for (const country of countries) {
  if ((country.region?.value ?? '').trim() === 'Aggregates') continue;
  const iso2 = (country.iso2Code ?? '').toUpperCase();
  if (!/^[A-Z]{2}$/.test(iso2)) continue;
  const fx = fcrf.values.get(country.id);
  const consumption = levelFrom(prvt.values.get(country.id), fx);
  const gdp = levelFrom(ppp.values.get(country.id), fx);
  const ok = (l) => l && l.ratio >= PLAUSIBLE[0] && l.ratio <= PLAUSIBLE[1];
  for (const [label, l] of [['consumption', consumption], ['gdp', gdp]]) if (l && !ok(l)) dropped.push(`${iso2} ${label} ${l.ratio.toPrecision(3)} (${l.year})`);
  const row = {};
  if (ok(consumption)) Object.assign(row, { c: Number(consumption.ratio.toFixed(3)), cy: consumption.year });
  if (ok(gdp)) Object.assign(row, { g: Number(gdp.ratio.toFixed(3)), gy: gdp.year });
  if (Object.keys(row).length > 0) rows[iso2] = row;
}

const fetchedAt = new Date().toISOString().slice(0, 10);
const keys = Object.keys(rows).sort();
const body = keys.map((k) => `  ${k}: ${JSON.stringify(rows[k]).replace(/"(\w+)":/g, '$1: ').replace(/,/g, ', ')},`).join('\n');
const years = keys.flatMap((k) => [rows[k].cy, rows[k].gy]).filter(Boolean);

writeFileSync(
  OUT,
  `/* GENERATED by apps/web/scripts/fetch-price-levels.mjs — do not edit by hand. Regenerate with \`node apps/web/scripts/fetch-price-levels.mjs\`. */

/**
 * Price level ratios (US = 1.0) by ISO 3166-1 alpha-2 code, from the World
 * Bank's World Development Indicators. \`c\` is the household final consumption
 * level (PA.NUS.PRVT.PP / PA.NUS.FCRF) and \`cy\` its year; \`g\` is the GDP
 * level (PA.NUS.PPP / PA.NUS.FCRF) and \`gy\` its year. A country missing here
 * has no published level in ${YEARS.replace(':', '–')} and is never guessed.
 */
export const PRICE_LEVEL_SOURCE = {
  name: 'World Bank, World Development Indicators',
  url: '${API}/country/all/indicator/{PA.NUS.PRVT.PP|PA.NUS.PPP|PA.NUS.FCRF}?format=json&date=${YEARS}',
  indicators: { consumption: 'PA.NUS.PRVT.PP / PA.NUS.FCRF', gdp: 'PA.NUS.PPP / PA.NUS.FCRF', equivalentTo: 'PA.NUS.PPPC.RF (archived)' },
  years: '${Math.min(...years)}–${Math.max(...years)}',
  sourceLastUpdated: '${fcrf.lastUpdated}',
  fetchedAt: '${fetchedAt}',
  countries: ${keys.length},
  /** Ratios outside ${PLAUSIBLE[0]}–${PLAUSIBLE[1]} the generator dropped rather than corrected. */
  dropped: ${JSON.stringify(dropped)} as readonly string[],
} as const;

export const PRICE_LEVELS: Readonly<Record<string, { c?: number; cy?: number; g?: number; gy?: number }>> = {
${body}
};
`,
);
process.stdout.write(`Wrote ${keys.length} countries to ${OUT}; dropped ${dropped.length}: ${dropped.join("; ")}\n`);
